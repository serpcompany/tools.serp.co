// Pure helpers for scripts/gone-tool-routes.mjs (issue #322): the retired
// Tool routes that middleware answers with 410 Gone. Owner decision D3 on
// #313: a retired Tool nobody searches for answers 410; one whose id has
// keyword demand keeps its 404 until it is rebuilt or dropped. The list is
// derived from the catalog and keywords.csv before every build and never
// committed, so a later retirement or rebuild changes it with nothing else to
// edit.

import { readFileSync } from "node:fs";
import path from "node:path";

import { toolHref } from "../../lib/catalog/href.ts";
import { parseKeywordsCsv } from "./keywords.mjs";
import { STATUS_INPUTS, keywordId } from "./tool-status.mjs";

// Where the build writes the list, from apps/tools. Gitignored; its committed
// type is gone-tool-routes.generated.d.ts beside it.
export const GONE_ROUTES_MODULE = "lib/gone-tool-routes.generated.js";

// The canonical (slashed) route of every retired Tool with no keyword demand,
// sorted. Demand is a keyword joining the Tool's id exactly (keywordId, the
// tool-status join) with a global volume above 0; alias keywords don't count.
// Only a Tool whose operation keywords.csv researched can show it has none:
// a retired Tool of any other operation (a downloader Lander, an editor, a
// viewer) has no row because nobody looked, so it keeps its 404, which is all
// D3 decided for it. A route that an active Tool also serves is never gone.
export function goneToolRoutes({ tools, keywords }) {
  const researched = new Set(keywords.map((row) => row.operation).filter(Boolean));
  const demanded = new Set(
    keywords.filter((row) => row.global_volume > 0).map((row) => keywordId(row.keyword)),
  );
  const live = new Set(tools.filter((tool) => tool.isActive).map(toolHref));
  const gone = tools
    .filter((tool) => !tool.isActive && researched.has(tool.operation) && !demanded.has(tool.id))
    .map(toolHref)
    .filter((route) => !live.has(route));
  return [...new Set(gone)].sort();
}

// The list for the catalog and keywords in this checkout.
export function readGoneToolRoutes(appRoot) {
  const read = (file) => readFileSync(path.join(appRoot, file), "utf8");
  return goneToolRoutes({
    tools: JSON.parse(read(STATUS_INPUTS.catalog)),
    keywords: parseKeywordsCsv(read(STATUS_INPUTS.keywords)),
  });
}

// The generated module's source: one route per line, so a build log or a
// local diff shows which routes changed.
export function goneRoutesModuleSource(routes) {
  return [
    "// Generated by scripts/gone-tool-routes.mjs before every build (issue #322)",
    "// from lib/catalog/tools.json and data/keywords.csv. Don't edit or commit it.",
    "export default [",
    ...routes.map((route) => `  ${JSON.stringify(route)},`),
    "];",
    "",
  ].join("\n");
}
