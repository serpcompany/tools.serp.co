// Writes lib/format-names.ts from content/formats.json: each format whose
// name there isn't its key in upper case ("webp" is "WebP"). Pages label a
// format with it without bundling the 100 KB reference into the Worker.
// content/formats.test.mjs fails when the file is out of date.
//
//   node apps/tools/scripts/format-names.mjs

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// The names the map holds: aliases ("jpeg", "tif") keep their own key, so
// "JPEG Compressor" stays JPEG.
export function formatNames(formats) {
  const names = {};
  for (const key of Object.keys(formats).sort()) {
    const { name } = formats[key];
    if (typeof name === "string" && name !== key.toUpperCase()) names[key] = name;
  }
  return names;
}

export function formatNamesSource(formats) {
  const entries = Object.entries(formatNames(formats)).map(
    ([key, name]) => `  ${/^[a-z_$][\w$]*$/i.test(key) ? key : JSON.stringify(key)}: ${JSON.stringify(name)},`,
  );
  return [
    "// Generated by apps/tools/scripts/format-names.mjs from content/formats.json;",
    "// don't edit. The formats whose name isn't their key in upper case.",
    "export const FORMAT_NAMES: Readonly<Record<string, string>> = {",
    ...entries,
    "};",
    "",
    '// A format as people write it: "WebP", "WebM", "MP4".',
    "export function formatName(format: string): string {",
    "  return FORMAT_NAMES[format] ?? format.toUpperCase();",
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const formats = JSON.parse(readFileSync(path.join(appRoot, "content/formats.json"), "utf8"));
  writeFileSync(path.join(appRoot, "lib/format-names.ts"), formatNamesSource(formats));
  console.log(`Wrote apps/tools/lib/format-names.ts (${Object.keys(formatNames(formats)).length} names).`);
}
